"""Read-only exact original ZIP/XML + bounded R4 saved quote quality on 20 historic cases.

The private R4 source audit must be regenerated by the existing pinned
first-party verifier. This adapter independently checks 20 EIS archives/notice
XML bytes and aggregates its source-verified 96 attachment / 47 quote results.
It NEVER accepts or changes prospective/blind gold, bids or legal decisions.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import xml.etree.ElementTree as ET
import zipfile
from collections import Counter
from pathlib import Path
from typing import Any

_SHA = re.compile(r"[a-f0-9]{64}\Z")
_NUMBER = re.compile(r"\d{19}\Z")
_EXACT = "EXACT_QUOTE_FROM_SAVED_TEXT_WITH_OFFICIAL_BINARY_SHA"
_NORMALIZED = "WHITESPACE_VARIANT_WITH_OFFICIAL_BINARY_SHA"
_UNSUPPORTED = "QUOTE_NOT_SUPPORTED_AS_LIVE_QUOTATION"
_VALID = {_EXACT, _NORMALIZED, _UNSUPPORTED}
_NEW_SOURCE_ROLE = "NEW_OFFICIAL_POSITIVE_REPLACEMENT"
_ROOT = Path(__file__).resolve().parents[2]
_MANIFEST = _ROOT / "docs/quality/APR067_R4_20_HISTORICAL_DEVELOPMENT_SOURCE_MANIFEST_2026-10-15.json"


class CohortEvidenceError(ValueError):
    """Reject unverifiable case, source, citation or unsafe filesystem input."""


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def load_json(path: Path, *, max_bytes: int = 2_000_000) -> tuple[dict, str]:
    if path.is_symlink() or not path.is_file() or not 0 < path.stat().st_size <= max_bytes:
        raise CohortEvidenceError("unsafe or missing source/evidence JSON")
    data = path.read_bytes()
    try:
        value = json.loads(data)
    except (ValueError, UnicodeError) as exc:
        raise CohortEvidenceError("unparseable source/evidence JSON") from exc
    if not isinstance(value, dict):
        raise CohortEvidenceError("source/evidence must be object")
    return value, digest(data)


def _local_name(tag: str) -> str:
    return tag.rsplit("}", 1)[-1]


def _xml_values(raw: bytes, tag: str) -> list[str]:
    if b"<!DOCTYPE" in raw.upper() or b"<!ENTITY" in raw.upper():
        raise CohortEvidenceError("unsafe XML declaration")
    try:
        tree = ET.fromstring(raw)
    except ET.ParseError as exc:
        raise CohortEvidenceError("invalid EIS notice XML") from exc
    return list(dict.fromkeys(
        (node.text or "").strip() for node in tree.iter()
        if _local_name(node.tag) == tag and (node.text or "").strip()
    ))


def check_original_zip(*, source_root: Path, entry: dict[str, Any]) -> dict[str, Any]:
    """Verify one case against first-party archived ZIP and selected notice XML."""
    number = entry.get("registry_number")
    if not isinstance(number, str) or not _NUMBER.fullmatch(number):
        raise CohortEvidenceError("invalid registry number")
    role = entry.get("source_role")
    if role not in {"ORIGINAL_20_CORPUS", _NEW_SOURCE_ROLE}:
        raise CohortEvidenceError("unsupported development source role")
    expected_zip, expected_xml = entry.get("archived_zip_sha256"), entry.get("selected_xml_sha256")
    if not all(isinstance(value, str) and _SHA.fullmatch(value) for value in (expected_zip, expected_xml)):
        raise CohortEvidenceError("source digest not SHA256")
    base = (source_root / "ai-expert-20261012/positive-eis-replacements-20261012"
            if role == _NEW_SOURCE_ROLE else source_root / "independent-20261012")
    file = base / number / "documentation-archive.zip"
    if (file.is_symlink() or not file.is_file() or
            not file.resolve().is_relative_to(source_root.resolve()) or
            file.stat().st_size > 100_000_000):
        raise CohortEvidenceError(f"official archived ZIP unavailable: {number}")
    blob = file.read_bytes()
    if digest(blob) != expected_zip:
        raise CohortEvidenceError(f"original ZIP SHA256 differs: {number}")

    matched = []
    with zipfile.ZipFile(file) as archive:
        candidates = archive.infolist()
        if len(candidates) > 200 or sum(c.file_size for c in candidates) > 100_000_000:
            raise CohortEvidenceError("unbounded ZIP members")
        for node in candidates:
            if not node.filename.lower().endswith(".xml"):
                continue
            if (node.file_size > 5_000_000 or node.is_dir() or
                    node.filename.startswith("/") or ".." in Path(node.filename).parts or "\\" in node.filename):
                raise CohortEvidenceError("unsafe XML archive member")
            raw = archive.read(node)
            if digest(raw) == expected_xml:
                matched.append(raw)
    if len(matched) != 1:
        raise CohortEvidenceError(f"selected archived XML not unique/unchanged: {number}")
    xml_raw = matched[0]
    if [x for x in _xml_values(xml_raw, "purchaseNumber") if _NUMBER.fullmatch(x)] != [number]:
        raise CohortEvidenceError(f"archived XML belongs to another procurement: {number}")
    xml_tree = ET.fromstring(xml_raw)
    attachment_count = sum(_local_name(node.tag) == "attachmentInfo" for node in xml_tree.iter())
    if (type(entry.get("selected_xml_attachment_references")) is not int or
            attachment_count != entry["selected_xml_attachment_references"]):
        raise CohortEvidenceError(f"XML attachment count not bound to selected edition: {number}")
    if entry.get("archived_version") is None or entry.get("competitive_method") not in (
        "COMPETITIVE_ELECTRONIC_AUCTION",
        "COMPETITIVE_ELECTRONIC_QUOTATIONS",
        "COMPETITIVE_OPEN_ELECTRONIC_COMPETITION",
    ):
        raise CohortEvidenceError(f"unsupported original competitive method: {number}")
    return {"number": number, "zip_sha256": expected_zip,
            "selected_xml_sha256": expected_xml, "original_attachment_refs": attachment_count}


def _ratio(num: int, den: int, basis: str) -> dict[str, Any]:
    if type(num) is not int or type(den) is not int or den < 1 or not 0 <= num <= den:
        raise CohortEvidenceError(f"invalid numerator/denominator: {basis}")
    return {"state": "OBSERVED_HISTORICAL_DEVELOPMENT_ONLY", "num": num, "den": den,
            "value": round(num / den, 6), "basis": basis}


def _unknown(reason: str) -> dict[str, Any]:
    return {"state": "NOT_MEASURED", "value": None, "reason": reason}


def quote_breakdown(audit: dict[str, Any]) -> dict[str, Any]:
    old = audit.get("saved_model_claims")
    new = audit.get("additional_four_cases_and_21_original_binaries")
    if not isinstance(old, dict) or not isinstance(new, dict):
        raise CohortEvidenceError("saved-model claims audit unavailable")
    old_rows = old.get("cases")
    new_rows = new.get("claim_checks")
    if not isinstance(old_rows, list) or not isinstance(new_rows, list):
        raise CohortEvidenceError("missing per-case verified claim receipts")
    checks = [check for case in old_rows for check in case.get("checks", [])]
    if any(not isinstance(r, dict) for r in checks + new_rows):
        raise CohortEvidenceError("invalid saved claims")
    counts = Counter(row.get("status") for row in checks)
    if set(counts) - _VALID or counts.get(None, 0):
        raise CohortEvidenceError("unsupported quote source status")
    for row in new_rows:
        if (type(row.get("quote_literal")) is not bool or
                type(row.get("quote_length_valid")) is not bool or
                type(row.get("claim_format_count_valid")) is not bool or
                not isinstance(row.get("registry_number"), str) or
                not _NUMBER.fullmatch(row["registry_number"])):
            raise CohortEvidenceError("new source claim missing verify flags")
        if not _SHA.fullmatch(str(row.get("original_binary_sha256"))) or not _SHA.fullmatch(str(row.get("original_text_sha256"))):
            raise CohortEvidenceError("new source claim not SHA bound")

    exact_old = counts[_EXACT]
    normalized = counts[_NORMALIZED]
    unsupported_old = counts[_UNSUPPORTED]
    exact_new = sum(row["quote_literal"] for row in new_rows)
    unsupported_new = len(new_rows) - exact_new
    if (len(checks) != old.get("claims") or len(new_rows) != new.get("model_claims_checked")
            or exact_old != old.get("literal_official_originals")
            or normalized != old.get("whitespace_variant_official_originals")
            or unsupported_old != old.get("unsubstantiated_literal_quotes")
            or exact_new != new.get("model_claims_exact_source_quotes")
            or unsupported_new != new.get("claims_requiring_quote_correction")
            or sum(not row["quote_length_valid"] for row in new_rows) != new.get("claims_breaching_quote_length_policy")):
        raise CohortEvidenceError("claimed quote totals differ from independently checked rows")
    all_count = len(checks) + len(new_rows)
    if all_count != audit.get("all_saved_model_claims_checked") or not all_count:
        raise CohortEvidenceError("wrong model quote denominator")
    return {
        "saved_quote_count": all_count,
        "exact_literal": exact_old + exact_new,
        "layout_only_difference": normalized,
        "unsupported_literal": unsupported_old + unsupported_new,
        "exact_quote_rate": _ratio(exact_old + exact_new, all_count, "selected_saved_model_quotes"),
        "source_supported_exact_or_layout": _ratio(exact_old + exact_new + normalized, all_count, "selected_saved_model_quotes"),
        "unsupported_quote_rate": _ratio(unsupported_old + unsupported_new, all_count, "selected_saved_model_quotes"),
        "overlong_quotes_in_new_subset": new["claims_breaching_quote_length_policy"],
        "new_claim_batches_exceeding_cap": new["model_batches_exceeding_claim_count_cap"],
        "legal_interpretation_verified": False,
    }


def evaluate(*, manifest: dict, audit: dict, source_root: Path, private_selection_sha256: str,
             public_audit_sha256: str, regenerated_audit_sha256: str) -> dict:
    if (manifest.get("schema_version") != "apr067-r4-historic-development-source-v1"
            or manifest.get("scope") != "R4_20_HISTORICAL_DEVELOPMENT_COMPETITIVE_44FZ_ONLY"
            or manifest.get("official_current_edition_asserted") is not False
            or manifest.get("legal_gold_signed") is not False
            or manifest.get("bid_ready") is not False
            or private_selection_sha256 != manifest.get("source_selection_sha256")
            or public_audit_sha256 != manifest.get("r4_audit_sha256")
            or regenerated_audit_sha256 != public_audit_sha256):
        raise CohortEvidenceError("development corpus origin is unpinned or substituted")
    cases = manifest.get("cases")
    if not isinstance(cases, list) or len(cases) != 20:
        raise CohortEvidenceError("expected exactly twenty historical competitive cases")
    if len({x.get("registry_number") for x in cases if isinstance(x, dict)}) != len(cases):
        raise CohortEvidenceError("duplicate development procurement")
    public_notices = audit.get("competitive_notices")
    negatives = audit.get("negative_controls")
    if not isinstance(public_notices, list) or not isinstance(negatives, list):
        raise CohortEvidenceError("audit lacks source cohort")
    if (len(public_notices) != 20 or len(negatives) != 4 or
            audit.get("source_cohort", {}).get("competitive") != 20 or
            audit.get("source_cohort", {}).get("negative") != 4 or
            audit.get("official_source_verified") != 21):
        raise CohortEvidenceError("wrong archived source cohort")
    published = {x["registry_number"]: x for x in public_notices}
    if len(published) != 20 or set(published) != {x["registry_number"] for x in cases}:
        raise CohortEvidenceError("published R4 audit and cohort manifest mismatch")
    original_results = []
    for entry in cases:
        result = check_original_zip(source_root=source_root, entry=entry)
        record = published[entry["registry_number"]]
        if (record.get("original_zip_sha256") != result["zip_sha256"]
                or record.get("original_xml_sha256") != result["selected_xml_sha256"]
                or record.get("archived_version") != entry["archived_version"]
                or record.get("method") != entry["competitive_method"]):
            raise CohortEvidenceError("per-notice audited original mismatch")
        original_results.append(result)
    references = sum(x["original_attachment_refs"] for x in original_results)
    published_coverage = audit.get("selected_original_notice_attachment_coverage")
    if (not isinstance(published_coverage, dict)
            or references != published_coverage.get("notice_attachment_references")
            or published_coverage.get("source_shas_attested") != references
            or published_coverage.get("case_count") != 20
            or sum(published_coverage.get("evidence_methods", {}).values()) != references):
        raise CohortEvidenceError("notice attachment coverage inconsistent")
    text = audit.get("selected_original_notice_text_availability")
    if (not isinstance(text, dict) or text.get("attachments_with_nonempty_source_text") != references
            or text.get("text_extraction_completeness_asserted") is not False):
        raise CohortEvidenceError("text availability flags invalid or overstated")
    quotations = quote_breakdown(audit)
    conflicts = audit.get("historical_model_report_deadline_audit")
    if (not isinstance(conflicts, dict) or conflicts.get("saved_reports_verified") != 10
            or type(conflicts.get("date_conflict_count")) is not int
            or type(conflicts.get("unattested_strong_blocker_decisions")) is not int):
        raise CohortEvidenceError("historical model report observations absent")
    if any(x.get("bid_ready") is not False for x in public_notices + negatives):
        raise CohortEvidenceError("source audit erroneously permits bids")
    return {
        "schema_version": "apr067-r4-20-development-evidence-v1",
        "scope": "20 historical competitive source cases; NOT 20 full new LLM E2E",
        "status": "REPRODUCED_20_OFFICIAL_ARCHIVED_SOURCES_AND_SAVED_CLAIM_CHECKS",
        "sample_cases": len(cases),
        "negative_source_controls": len(negatives),
        "official_zip_xml_verified_now": original_results,
        "r4_firstparty_original_attachment_source_audit_reexecuted": {
            "attested": references, "total": references,
            "source": "R4 private SHA-pinned build_review re-executed, not new independent 96-download",
        },
        "r4_saved_quote_evidence": quotations,
        "historic_model_report_warnings": {
            "saved_reports": conflicts["saved_reports_verified"],
            "archival_date_conflicts": conflicts["date_conflict_count"],
            "unattested_strong_blocker_decisions": conflicts["unattested_strong_blocker_decisions"],
        },
        "metrics": {
            "zip_sha_matched": _ratio(len(original_results), len(cases), "historical_EIS_ZIPs"),
            "registry_matching_selected_XML_sha_matched": _ratio(len(original_results), len(cases), "historical_EIS_notice_XML"),
            "archived_notice_attachment_refs_attested_by_R4": _ratio(references, references, "R4_pinned_originals"),
            "saved_source_quote_exact": quotations["exact_quote_rate"],
            "saved_source_quote_unsupported": quotations["unsupported_quote_rate"],
            "all_material_claim_truth": _unknown("only selected literal snippets evaluated, no full semantic legal assertions"),
            "independent_human_gold": _unknown("qualified signed legal judgment not collected"),
            "operator_full_e2e_completion_rate": _unknown("twenty archived sources are NOT twenty fresh UI/LLM workflow E2Es"),
            "rolling_slo_latency": _unknown("no complete multi-case timing distribution"),
            "current_official_revision_verified": _unknown("archived source snapshot only"),
        },
        "public_manifest_sha256": digest(json.dumps(manifest,sort_keys=True,ensure_ascii=False).encode("utf-8")),
        "r4_recomputed_audit_sha256": regenerated_audit_sha256,
        "source_selection_sha256": private_selection_sha256,
        "bid_ready": False, "legal_gold_signed": False,
        "production_or_model_promotion_authorized": False,
    }


def main() -> int:
    cli = argparse.ArgumentParser()
    cli.add_argument("--manifest", type=Path, default=_MANIFEST)
    cli.add_argument("--source-root", type=Path, required=True)
    cli.add_argument("--r4-recomputed-audit", type=Path, required=True)
    cli.add_argument("--output", type=Path, required=True)
    opts = cli.parse_args()
    manifest, _ = load_json(opts.manifest, max_bytes=250_000)
    original = opts.source_root.resolve()
    if not original.is_dir() or original.is_symlink():
        cli.error("private first-party development source root absent")
    selection = original / "ai-expert-20261012/positive-eis-replacements-20261012/verified-competitive-20-plus-four-negative.json"
    try:
        _, selection_sha = load_json(selection)
        audit, audit_sha = load_json(opts.r4_recomputed_audit)
        result = evaluate(
            manifest=manifest, audit=audit, source_root=original,
            private_selection_sha256=selection_sha,
            public_audit_sha256=manifest["r4_audit_sha256"],
            regenerated_audit_sha256=audit_sha,
        )
        folder = Path("/Volumes/ArvectumSSD/Arvectum/runtime/ta-apr067-r4-development-source-quality-20261015").resolve()
        output = opts.output.resolve()
        if not folder.is_dir() or output.parent != folder:
            raise CohortEvidenceError("output must stay in the private dedicated R4 development quality directory")
        with output.open("x", encoding="utf-8") as stream:
            json.dump(result, stream, ensure_ascii=False, indent=2, sort_keys=True)
            stream.write("\n")
    except (CohortEvidenceError, OSError, ValueError, KeyError, zipfile.BadZipFile) as exc:
        print(f"APR067_R4_BLOCKED: {type(exc).__name__}: {exc}")
        return 2
    quote = result["r4_saved_quote_evidence"]
    print(json.dumps({
        "status": result["status"],
        "cases": result["sample_cases"],
        "attachment_refs": result["r4_firstparty_original_attachment_source_audit_reexecuted"]["attested"],
        "model_snippets": quote["saved_quote_count"],
        "exact": quote["exact_literal"],
        "layout_variant": quote["layout_only_difference"],
        "unsupported_literal": quote["unsupported_literal"],
    }, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
